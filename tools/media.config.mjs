// media.config.mjs — какие кадры из выгрузки VK идут на сайт.
//
// Исходники лежат в vk-media/ (в git не попадают: 2 ГБ личного
// архива). `npm run media` режет их под пропорции секций, прогоняет
// через единую обработку и кладёт готовые AVIF/WebP/JPEG в
// public/assets/img/, видео — в public/assets/video/, а размеры —
// в src/data/media.json.
//
// Поля:
//   key    — путь результата без расширения: 'combat/1' →
//            public/assets/img/combat/1-<ширина>.<avif|webp|jpg>
//   src    — фото относительно vk-media/
//   video  — либо кадр из видео: файл + секунда `t` (берётся самый
//            резкий кадр в окне ±window, по умолчанию ±0,4 с)
//   ratio  — пропорции кадра [ширина, высота]
//   fx, fy — точка, вокруг которой режем (0…1), по умолчанию центр
//   zoom   — >1: кадр крупнее (режем меньшую область исходника)
//   widths — ширины для srcset; больше исходника не растягиваем
//   soft   — принудительно включить/выключить усиленную резкость
//   quality — качество AVIF (по умолчанию 48), для LCP-картинки ниже
//   post   — откуда кадр (для docs/media-sources.md)
//
// Правило отбора: только чёткие кадры, где с первого взгляда ясно,
// что происходит. Групповые снимки детей в плавках (бассейн, баня),
// коллажи, открытки, скриншоты и кадры с наложенным текстом на сайт
// не берутся. Бассейн показан только общим планом, где людей не узнать.
// ================================================================

